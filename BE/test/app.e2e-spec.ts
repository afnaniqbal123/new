import { Test, TestingModule } from '@nestjs/testing';
import { INestApplication } from '@nestjs/common';
import request from 'supertest';
import { App } from 'supertest/types';
import { AppModule } from './../src/app.module';

describe('AppController (e2e)', () => {
  let app: INestApplication<App>;

  // `beforeAll`, not `beforeEach`: booting the whole AppModule opens a real
  // Mongo connection, and doing it per test multiplied the cost for no gain.
  beforeAll(async () => {
    const moduleFixture: TestingModule = await Test.createTestingModule({
      imports: [AppModule],
    }).compile();

    app = moduleFixture.createNestApplication();
    await app.init();
  });

  // Without this the connection stays open after the suite finishes, Jest
  // cannot exit, and the whole e2e run hangs or times out depending on what
  // else is running alongside. It shows up as an unrelated suite failing.
  afterAll(async () => {
    await app.close();
  });

  it('/ (GET)', () => {
    return request(app.getHttpServer())
      .get('/')
      .expect(200)
      .expect('Hello World!');
  });
});
